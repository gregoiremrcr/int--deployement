-- Likes anonymes par Pokémon.
-- visitor_id doit être généré côté client et conservé dans un cookie/localStorage.
create table if not exists public.pokemon_likes (
  id bigint generated by default as identity primary key,
  pokemon_id integer not null check (pokemon_id > 0),
  visitor_id text not null check (btrim(visitor_id) <> ''),
  created_at timestamptz not null default timezone('utc', now()),
  constraint pokemon_likes_pokemon_visitor_unique
    unique (pokemon_id, visitor_id)
);

create index if not exists pokemon_likes_pokemon_id_idx
  on public.pokemon_likes (pokemon_id);

alter table public.pokemon_likes enable row level security;

drop policy if exists "pokemon likes are readable" on public.pokemon_likes;
create policy "pokemon likes are readable"
on public.pokemon_likes
for select
to anon, authenticated
using (true);

drop policy if exists "pokemon likes can be added" on public.pokemon_likes;
create policy "pokemon likes can be added"
on public.pokemon_likes
for insert
to anon, authenticated
with check (true);

drop policy if exists "pokemon likes can be removed" on public.pokemon_likes;
create policy "pokemon likes can be removed"
on public.pokemon_likes
for delete
to anon, authenticated
using (true);

grant usage on schema public to anon, authenticated;
grant select, insert, delete on table public.pokemon_likes to anon, authenticated;
